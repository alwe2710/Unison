#!/usr/bin/env bash
# Writes version_generated.js from `git describe --tags --always --dirty`
# -- run this after tagging a release (or whenever you want the Settings
# "Info" panel's version string to catch up); a normal checkout doesn't
# need to (version_generated.js is committed, same "manually run, commit
# the generated output" convention as i18n/generate.py's
# strings_generated.js and build_wasm.sh's unison_core.js in this
# directory -- there's no build/deploy step here to hook this into
# automatically, see this directory's README).
#
# Same mechanism as the Android/3DS/Switch/iOS clients' own
# UNISON_APP_VERSION/gitDescribe (see their build files' comments), just
# run by hand instead of at build time, since this client has no build
# step at all.
set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")"

VERSION=$(git describe --tags --always --dirty 2>/dev/null || true)
if [ -z "$VERSION" ]; then
  VERSION="unknown"
fi

cat > version_generated.js <<EOF
// Generated by generate_version.sh from \`git describe\` -- do not edit by
// hand, re-run that script to refresh it. See its own comment for why
// this is committed (manually regenerated) rather than produced at a
// build step, unlike every other client's version string.
const UNISON_APP_VERSION = "$VERSION";
EOF

echo "Wrote version_generated.js: UNISON_APP_VERSION = \"$VERSION\""
